#!/usr/bin/env python3
"""Mirror Ezra's send record (OneDrive School Duty/sent.json) into the board.

Copies only board-reservation entries (reservation id, kind, date, sender) to
src/api/_sent-elsewhere-data.js, commits and pushes to main when it changed, so
the board's morning run skips tests Ezra already emailed. No names: the repo
is public. Prints one line. Exit 1 on any problem; never writes a partial file.
"""
import json, pathlib, subprocess, sys

REPO = pathlib.Path(__file__).resolve().parents[1]
OUT = REPO / "src/api/_sent-elsewhere-data.js"
REMOTE = "onedrive:바탕 화면/Real Backup/Agents/School Duty/sent.json"
RCLONE = str(pathlib.Path.home() / "bin/rclone")


def git(*a):
    return subprocess.run(["git", "-C", str(REPO), *a], capture_output=True, text=True, check=True).stdout


def main():
    push = "--no-push" not in sys.argv
    raw = subprocess.run([RCLONE, "cat", REMOTE], capture_output=True, text=True, timeout=120)
    if raw.returncode:
        print("sync-sent-elsewhere: could not read sent.json:", raw.stderr.strip()[-200:]); return 1
    sends = json.loads(raw.stdout).get("sends")
    if not isinstance(sends, list):
        print("sync-sent-elsewhere: sent.json has no sends list"); return 1
    keep = sorted(({"reservation": e["reservation"], "kind": e.get("kind", ""),
                    "at": e.get("at", ""), "by": e.get("by", "Ezra")}
                   for e in sends if e.get("reservation") and e["reservation"] != "manual"),
                  key=lambda e: (e["at"], e["reservation"], e["kind"]))
    text = ("// Generated by tools/sync-sent-elsewhere.py from School Duty/sent.json. Do not edit.\n"
            "export default " + json.dumps(keep, indent=1, ensure_ascii=False) + ";\n")
    if OUT.exists() and OUT.read_text() == text:
        print(f"sync-sent-elsewhere: unchanged ({len(keep)} entries)"); return 0
    OUT.write_text(text)
    if not push:
        print(f"sync-sent-elsewhere: wrote {len(keep)} entries (not pushed)"); return 0
    git("add", str(OUT.relative_to(REPO)))
    git("commit", "-q", "-m", f"sent-elsewhere: sync {len(keep)} entries from School Duty/sent.json")
    git("push", "-q", "origin", "HEAD:main")
    print(f"sync-sent-elsewhere: pushed {len(keep)} entries"); return 0


if __name__ == "__main__":
    sys.exit(main())
