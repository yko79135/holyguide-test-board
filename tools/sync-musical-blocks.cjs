#!/usr/bin/env node
/* Rebuilds src/api/_musical-blocks.js from Mr. Ko's live schedule.
 *
 * Mr. Ko (2026-11-13): "block students from booking slots that you know a
 * musical practice is scheduled for that student." The live schedule site
 * (mrko-live-schedule, private repo, kept current by Ezra from the
 * rehearsal Doc and the teachers' KakaoTalk) already knows every rehearsal,
 * its time and which grades it takes. This copies only what the board
 * needs — date, start, end, grades — into this public repo. No names.
 *
 * Usage: node tools/sync-musical-blocks.cjs <path to mrko-live-schedule/data.js> [fromISO]
 * Rows without a time, and rows for the 4 leads only (grades = []), are
 * skipped: the board cannot tell which students those are.
 */
const fs = require('node:fs');
const path = require('node:path');

const src = process.argv[2];
if (!src) { console.error('usage: sync-musical-blocks.cjs <data.js> [fromISO]'); process.exit(2); }
const D = require(path.resolve(src));
const from = process.argv[3] || '0000-00-00';

const blocks = D.MUS
  .filter((m) => m.s && m.e && m.d >= from && Array.isArray(m.g) && m.g.length)
  .map((m) => ({ d: m.d, s: m.s, e: m.e, g: [...m.g].sort((a, b) => a - b) }))
  .sort((a, b) => (a.d + a.s).localeCompare(b.d + b.s));

const out = '/* Musical rehearsals that take students out of class — generated by\n' +
  '   tools/sync-musical-blocks.cjs from Mr. Ko\'s live schedule (updated ' + D.UPDATED + ').\n' +
  '   d = date, s/e = start/end (KST), g = grade numbers taken out.\n' +
  '   Do not edit by hand; re-run the tool. */\n' +
  'export default ' + JSON.stringify(blocks, null, 0).replace(/\},\{/g, '},\n  {').replace(/^\[/, '[\n  ').replace(/\]$/, '\n]') + ';\n';

const dest = path.join(__dirname, '..', 'src', 'api', '_musical-blocks.js');
const before = fs.existsSync(dest) ? fs.readFileSync(dest, 'utf8') : '';
if (before === out) { console.log('unchanged (' + blocks.length + ' rehearsals)'); process.exit(0); }
fs.writeFileSync(dest, out);
console.log('wrote ' + blocks.length + ' rehearsals to ' + path.relative(process.cwd(), dest));
